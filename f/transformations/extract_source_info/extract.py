"""
EXTRACT_SOURCE_INFO - Извлечение библиографической информации

ЧТО ДЕЛАЕТ:
- Извлекает данные о книге или научной статье из произвольных входных данных
- Форматирует результат в стандартном библиографическом формате

ГДЕ ИСПОЛЬЗУЕТСЯ:
- Используется как часть линтера для создания библиографических ссылок

ИСПОЛЬЗУЕТ:
- Resource: u/theatmacreator/finer_c_openrouter
- Shared: f/shared/llm_utils
"""
import wmill
from f.shared.llm_utils import create_llm_client, generate_completion


def main(
    input: str,
    model: str = "openai/chatgpt-4o-latest"
) -> dict:
    """
    Извлекает библиографическую информацию из произвольных данных.

    @param input Произвольные данные о книге или статье
    @param model Модель для использования
    @return Словарь с полем output - отформатированная библиографическая ссылка
    """
    resource = wmill.get_resource("u/theatmacreator/finer_c_openrouter")
    client = create_llm_client(resource)

    prompt = f"""# Роль
Ты лучший эксперт по извлечению и упорядочиванию данных.

# Задача
Пользователь передает тебе произвольные входные данные о книге или научной статье. Твоя задача найти в этих данных информацию о :
- названии работы
- авторе
- годе публикации
- месте публикации
- издателе

Сделай глубокий вдох и подумай очень хорошо, от этого зависит моя карьера.

# Правила
- Если входные данные переданы на английском ответ должен быть долностью на английском языке.
- Если входные данные переданы на русском ответ должен быть долностью на русском языке.
- Если город издания не указан добавь город соответствующий издателю.
- Если авторов несколько нужно указать всех.
- Если передан диапазон страниц добавь его в конце в одном из двух форматов в зависимости от языка \"с. страницы\", \"p. страницы\"

# Формат ответа для информации о книге
Фамилия_автора и сокращенные_инициалы_автора, название_книги - город_издания, издательство, год_издания, с.

Пример : Виноградов М. И., Физиология трудовых процессов - Москва , Медицина , 1966

# Формат ответа для информации о научной статье
Фамилия_автора и сокращенные_инициалы_автора, название_работы, название_источника, другие_данные_источника, год, страницы_работы_если_переданы

Пример : Bruce М., The effect of lessening the drive upon the performance by white rats
in a maze, J. Comp. Psychol., 25, 1938

Конец инструкций.

# Входные данные
{input}
"""

    result = generate_completion(
        client=client,
        prompt=prompt,
        model=model,
        temperature=0.5,
    )

    return {"output": result}
