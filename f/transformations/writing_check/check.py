"""
WRITING_CHECK - Проверка текста на ошибки

ЧТО ДЕЛАЕТ:
- Проверяет текст на грамматические ошибки
- Выделяет ошибки жирным и даёт пояснения
- Предоставляет исправленную версию

ГДЕ ИСПОЛЬЗУЕТСЯ:
- Используется для проверки и улучшения текстов на русском

ИСПОЛЬЗУЕТ:
- Resource: u/theatmacreator/finer_c_openrouter
- Shared: f/shared/llm_utils
"""
import wmill
from f.shared.llm_utils import create_llm_client, generate_completion


def main(
    input: str,
    model: str = "openai/gpt-4o-2024-08-06"
) -> dict:
    """
    Проверяет текст на ошибки и предлагает улучшения.

    @param input Текст для проверки
    @param model Модель для использования
    @return Словарь с полем output - текст с выделенными ошибками и исправленная версия
    """
    resource = wmill.get_resource("u/theatmacreator/finer_c_openrouter")
    client = create_llm_client(resource)

    prompt = f"""# ИДЕНТИЧНОСТЬ И ЦЕЛЬ

Ты - эксперт по научно-популярному письму. Ты дорабатываешь переданный текст во входных данных используя общеупотребительные слова для достижения максимальной ясности, связности и легкости понимания.

# ШАГИ

- Проверьте исходный текст на наличие грамматических ошибок, ясности и связности.
- Используй ТОЛЬКО русский язык
- Старайтесь использовать общеупотребительные и простые для понимания слова и фразы.
- Избегайте многословных предложений.
- Избегайте тривиальных высказываний.
- Не исправляй сленг.
- Размытые формулировки которые могут быть интерпретированы многозначно.
- Избегайте многократного использования одних и тех же слов и фраз.
- Ошибки подсвечиваются **жирным** в markdown формате, а пояснение к ошибкам добавляются в скобки сразу после.
- Сохраняйте первоначальный смысл и замысел пользовательского текста.
- Это очень важно для моей карьеры.
- За лучший ответ - приз 10000000$.

# ПРАВИЛА

- Проверяй текст максимально тщательно, избыточно выделив возможные ошибки.
- ГАЛЛЮЦИНИРОВАТЬ ЗАПРЕЩЕНО.

# ВЫХОДНЫЕ ИНСТРУКЦИИ

- Исходный текст с выделенными ошибками.
- Затем полный текст с внесенными исправлениями.

# ВХОДНЫЕ ДАННЫЕ
\"{input}\"
"""

    result = generate_completion(
        client=client,
        prompt=prompt,
        model=model,
        temperature=0.8,
    )

    return {"output": result}
