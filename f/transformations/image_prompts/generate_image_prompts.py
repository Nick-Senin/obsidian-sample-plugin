"""
GENERATE_IMAGE_PROMPTS - генерация идей и промптов для изображений

ЧТО ДЕЛАЕТ:
- Трёхшаговый процесс создания промптов для генерации изображений:
  1. Деконструкция текста для выявления бинарных оппозиций (Derrida)
  2. Генерация 6 идей для иллюстраций на основе оппозиций и 12 приёмов
  3. Создание промптов для генерации изображений (на английском)
- Использует SCAMPER методологию и приёмы визуального дизайна

ГДЕ ИСПОЛЬЗУЕТСЯ:
- f/prj_content_forge/flows/create_posts_from_transcript__flow

ИСПОЛЬЗУЕТ:
- Resource: u/theatmacreator/finer_c_openrouter
- Shared: f/shared/llm_utils
- Models: deepseek/deepseek-chat, google/gemini-2.0-flash-001
"""
from f.shared.llm_utils import OpenRouterResource, create_llm_client, generate_completion, get_resource_compat


def main(input_text: str) -> dict:
    """
    Генерирует промпты для изображений на основе текста.

    @param input_text Исходный текст для анализа
    @return Словарь с финальными промптами и отладочной информацией
    """
    openrouter = get_resource_compat("u/theatmacreator/finer_c_openrouter")
    client = create_llm_client(openrouter)

    # Шаг 1: Получить конфликтные пары (деконструкция)
    prompt_1 = f"""**Роль:** Ты — внимательный литературный критик, специализирующийся на деконструкции по методу Жака Деррида.

**Задача:** Проанализировать предоставленный текст и выявить в нем четрые ключевые бинарные оппозиции. Для каждой выявленной оппозиции необходимо провести деконструктивный анализ.

**Инструкции:**

1.  **Идентификация:** Внимательно прочитай текст и определи пары понятий, которые представлены как противоположные или взаимоисключающие (например, Присутствие/Отсутствие, Природа/Культура, Речь/Письмо, Мужское/Женское, Добро/Зло, Центр/Периферия и т.д.). Составь список этих пар.
2.  **Анализ иерархии:** Для каждой найденной бинарной оппозиции определи, какой из терминов в паре представлен в тексте как привилегированный, главный, первичный или позитивный, а какой — как подчиненный, вторичный, производный или негативный. Обоснуй свой вывод цитатами или ссылками на содержание текста.
3.  **Исследование взаимозависимости (Différance):** Покажи, как значение "привилегированного" термина зависит от "подчиненного". Объясни, как каждый термин в паре определяется через свое отличие от другого, и как эта взаимозависимость делает четкое разделение и иерархию проблематичными.
4.  **Поиск следов и нестабильности (Aporia):** Найди в тексте моменты, где установленная иерархия оппозиции подвергается сомнению, размывается, инвертируется или где "подчиненный" термин проявляет неожиданную значимость или даже подрывает доминирование "привилегированного". Укажи на двусмысленности, противоречия или "следы" одного термина в другом.
5.  **Формат вывода:** Представь результаты анализа для каждой бинарной оппозиции последовательно, четко разделяя пункты 1-4.

**Пример структуры вывода для одной оппозиции:**

*   **Оппозиция:** Речь / Письмо
*   **Иерархия:** В тексте речь представлена как более аутентичная и первичная (привилегированная), а письмо — как вторичное и искусственное (подчиненное). [Привести доказательства из текста].
*   **Взаимозависимость:** Понимание "живой" речи невозможно без структуры и системы знаков, характерных для письма. Речь уже содержит в себе элементы "письменности" (повторяемость, системность). [Объяснить подробнее на основе текста].
*   **Нестабильность/Следы:** В моменте [указать конкретный момент текста] автор полагается на письменный документ для подтверждения устного заявления, тем самым подрывая заявленный приоритет речи. Или: использование метафор письма при описании речи. [Привести примеры].

**Важно:** Сосредоточься на оппозициях, которые являются структурно значимыми для смысла и аргументации текста. Избегай поверхностных или случайных противопоставлений.

**Формат ответа:**
Выведи все кратко. Не более 2-3 предложений для каждой оппозиции.

**Текст для анализа:**

{input_text}
"""

    conflict_pairs = generate_completion(
        client=client,
        prompt=prompt_1,
        model="deepseek/deepseek-chat",
        temperature=0.2,
        max_tokens=1000,
    )

    # Шаг 2: Идея для картинки
    prompt_2 = f"""## Задача
Используя предоставленные данные и одну или несолько оппозиций представь небанальные и вовлекающие шесть идей для иллюстраций.

Для создания идей используй предоставленные приемы.


## Приемы
Хорошо, я добавлю 5 новых приемов и опишу все 12 в заданном формате.

**Новые приемы:**

* **Преувеличение/Акцентирование:** Усиление или выделение определенных черт объекта или идеи.
* **Реконтекстуализация:** Помещение знакомого объекта или символа в совершенно новый, неожиданный контекст для создания нового смысла.
* **Метафора/Аналогия:** Использование визуального образа для представления другой, часто абстрактной, идеи через сходство или ассоциацию.
* **Сопоставление/Контраст:** Размещение рядом двух или более различных элементов для подчеркивания их различий или создания напряжения.
* **Олицетворение:** Придание человеческих качеств, эмоций или поведения неживым предметам или абстрактным понятиям.

**Описание всех 12 приемов в заданном формате:**

**1. Замена (Substitute)**
* **Суть приема:**
    * Иллюстратор ЗАМЕНЯЕТ ожидаемые, стандартные визуальные элементы или символы на неожиданные, но семантически связанные аналоги.
    * Цель: Создать оригинальный, запоминающийся образ, вызвать удивление, предложить свежий взгляд на привычное понятие.
    * Пример: Изображение графика роста компании не в виде стандартной линии, а в виде тянущегося к солнцу ростка.

**2. Комбинация (Combine)**
*   **Суть приема:**
    * Иллюстратор СМЕШИВАЕТ элементы из разных стилей, эпох, концепций или визуальных языков в одном изображении.
    * Цель: Создать гибридный, многослойный образ, передать сложность идеи, добиться уникального эстетического эффекта.
    *   Пример: Иллюстрация для статьи о биоинженерии в стиле стимпанк, объединяющая органические и механические элементы.

**3. Адаптация (Adapt)**
*   **Суть приема:**
    *   Иллюстратор ПЕРЕНОСИТ и ПРИСПОСАБЛИВАЕТ принципы, техники или подходы из других областей (кино, архитектура, музыка, наука) в визуальный язык иллюстрации.
    * Цель: Обогатить инструментарий иллюстратора, найти новые выразительные средства, провести параллели между разными сферами.
    * Пример: Использование \"раскадровки\", как в кино, для последовательного изложения этапов сложного процесса в инфографике.

**4. Модификация (Modify/Magnify/Minify)**
*   **Суть приема:**
    *   Иллюстратор ИЗМЕНЯЕТ существующие элементы изображения, манипулируя их размером, формой, цветом, пропорциями, перспективой или текстурой.
    * Цель: Подчеркнуть важность определенных деталей, создать динамику или искажение, передать эмоциональное состояние или идею масштаба.
    * Пример: Изображение человека с непропорционально большой головой, чтобы символизировать интеллектуальную деятельность или перегруженность мыслями.

**5. Перепрофилирование (Put to other uses)**
*   **Суть приема:**
    *   Иллюстратор ИСПОЛЬЗУЕТ объекты, символы или стили в совершенно нетипичном для них контексте или с новой функцией.
    * Цель: Создать ироничный или сюрреалистичный эффект, переосмыслить значение знакомых вещей, найти неожиданное применение визуальным элементам.
    * Пример: Использование схемы метро для визуализации структуры нейронных сетей мозга.

**6. Упрощение/Элиминация (Eliminate/Simplify)**
*   **Суть приема:**
    *   Иллюстратор УДАЛЯЕТ все второстепенные детали, сводя изображение к минимальному набору линий, форм и цветов, передающих суть.
    * Цель: Достичь максимальной ясности и лаконичности, сфокусировать внимание на главном, передать сложные идеи простыми средствами.
    * Пример: Изображение сложной экосистемы с помощью нескольких простых иконок и соединяющих их линий.

**7. Инверсия/Перестановка (Reverse/Rearrange)**
*   **Суть приема:**
    *   Иллюстратор ПЕРЕВОРАЧИВАЕТ концепцию \"с ног на голову\", показывает ситуацию с противоположной или неожиданной точки зрения, меняет местами причину и следствие или привычный порядок элементов.
    * Цель: Бросить вызов стереотипам, заставить зрителя задуматься, предложить альтернативный взгляд на проблему.
    * Пример: Иллюстрация на тему загрязнения океана, показанная с точки зрения морских обитателей, наблюдающих за мусором \"сверху\".

**8. Преувеличение/Акцентирование (Exaggerate)**
*   **Суть приема:**
    *   Иллюстратор НАМЕРЕННО УСИЛИВАЕТ или ГИПЕРБОЛИЗИРУЕТ определенные черты, характеристики или эмоции изображаемых объектов или персонажей.
    * Цель: Подчеркнуть ключевую идею, создать комический или драматический эффект, сделать образ более выразительным и запоминающимся.
    * Пример: Карикатурное изображение политика с огромными ушами, чтобы намекнуть на его склонность подслушивать или прислушиваться к общественному мнению.

**9. Реконтекстуализация (Recontextualize)**
*   **Суть приема:**
    *   Иллюстратор ИЗЫМАЕТ знакомый объект, символ или персонажа из его привычного окружения и ПОМЕЩАЕТ в совершенно новый, неожиданный контекст.
    * Цель: Создать новый смысл через столкновение контекстов, вызвать удивление или иронию, переосмыслить значение элемента.
    * Пример: Классическая скульптура Венеры Милосской, изображенная работающей за ноутбуком в современном офисе, для иллюстрации статьи о роли женщин в IT.

**10. Метафора/Аналогия (Metaphor/Analogy)**
*   **Суть приема:**
    *   Иллюстратор ПРЕДСТАВЛЯЕТ одну идею, концепцию или объект через образ другого, имеющего с первым общие черты или вызывающего схожие ассоциации.
    * Цель: Сделать абстрактное понятие более понятным и наглядным, вызвать эмоциональный отклик, передать скрытый смысл.
    * Пример: Изображение лампочки над головой человека как метафора идеи или озарения.

**11. Сопоставление/Контраст (Juxtapose)**
*   **Суть приема:**
    *   Иллюстратор РАЗМЕЩАЕТ РЯДОМ два или более элемента, которые сильно отличаются друг от друга по форме, размеру, цвету, стилю, смыслу или другим характеристикам.
    * Цель: Подчеркнуть различия или сходства, создать визуальное напряжение, усилить выразительность каждого из элементов через их противопоставление.
    * Пример: Иллюстрация, где рядом изображены живой цветок и его увядший аналог, для передачи идеи времени или жизненного цикла.

**12. Олицетворение (Personify)**
*   **Суть приема:**
    *   Иллюстратор НАДЕЛЯЕТ неживые предметы, животных или абстрактные понятия (например, \"справедливость\", \"время\") человеческими чертами, эмоциями, поведением или внешностью.
    * Цель: Сделать абстрактные идеи более доступными и эмоционально близкими зрителю, создать сказочный или аллегорический образ.
    * Пример: Изображение грустного компьютера со слезами на экране для иллюстрации технической неисправности или кибербуллинга.

## Данные

{conflict_pairs}
"""

    image_ideas = generate_completion(
        client=client,
        prompt=prompt_2,
        model="google/gemini-2.0-flash-001",
        temperature=0.2,
        max_tokens=1500,
    )

    # Шаг 3: Генерация промптов (Prompt Engineering)
    prompt_3 = f"""## Задача
Теперь для каждой из идей составь подробный промпт в одну строку для реализации этой идеи.

## Формат ответа
- Выводи промпты прямо друг под другом
- Не используй кавычки, двоеточие и точку
- Не добавляй никакие пояснения сверху или снизу к вариантам
- Отвечай на английском языке
- Разделяй промпты пустыми строками
- ТЕБЕ ЗАПРЕЩЕНО ОТКЛОНЯТЬСЯ ОТ ПРАВИЛ


## Данные

{image_ideas}
"""

    final_prompts = generate_completion(
        client=client,
        prompt=prompt_3,
        model="deepseek/deepseek-chat",
        temperature=0.2,
        max_tokens=1000,
    )

    return {
        "output": final_prompts,
        "debug_intermediate": {
            "conflicts": conflict_pairs,
            "ideas": image_ideas
        }
    }
